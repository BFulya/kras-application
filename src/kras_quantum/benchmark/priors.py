logger = logging.getLogger(__name__)

__all__ = ["BenchmarkResult", "PriorComparison", "run_prior_benchmark", "run_qubit_sweep"]


@dataclass
class BenchmarkResult:
    """Tek bir yapilandirmanin tekrarli olcum sonucu."""

    label: str
    local_filter_rates: list[float] = field(default_factory=list)
    chemistry42_rates: list[float] = field(default_factory=list)
    uniqueness: list[float] = field(default_factory=list)
    n_qubits: int | None = None
    duration_s: float = 0.0

    # --- ozetler (Makale: Mean +/- Std) ---
    @property
    def local_mean(self) -> float:
        return float(np.mean(self.local_filter_rates)) if self.local_filter_rates else 0.0

    @property
    def local_std(self) -> float:
        return float(np.std(self.local_filter_rates)) if self.local_filter_rates else 0.0

    @property
    def chemistry42_mean(self) -> float:
        return float(np.mean(self.chemistry42_rates)) if self.chemistry42_rates else 0.0

    @property
    def chemistry42_std(self) -> float:
        return float(np.std(self.chemistry42_rates)) if self.chemistry42_rates else 0.0

    @property
    def uniqueness_mean(self) -> float:
        return float(np.mean(self.uniqueness)) if self.uniqueness else 0.0

    def as_dict(self) -> dict:
        return {
            "label": self.label,
            "n_qubits": self.n_qubits,
            "local_filter_mean": self.local_mean,
            "local_filter_std": self.local_std,
            "chemistry42_mean": self.chemistry42_mean,
            "chemistry42_std": self.chemistry42_std,
            "uniqueness_mean": self.uniqueness_mean,
            "n_repeats": len(self.local_filter_rates),
            "duration_s": self.duration_s,
        }

    def __str__(self) -> str:  # pragma: no cover
        return (
            f"{self.label:<16} "
            f"local {self.local_mean:5.2f} +/- {self.local_std:4.2f} % | "
            f"chem42 {self.chemistry42_mean:5.2f} +/- {self.chemistry42_std:4.2f} % | "
            f"benzersiz {self.uniqueness_mean:5.1f} %"
        )


@dataclass
class PriorComparison:
    """Tum yapilandirmalarin karsilastirmasi."""

    results: list[BenchmarkResult] = field(default_factory=list)

    def quantum_advantage(self) -> dict[str, float]:
        """Kuantum kollarin klasik taban cizgiye gore goreli iyilesmesi.

        Makale, QCBM-LSTM icin "a 21.5% improvement in passing filters"
        bildirir (Supplementary Table 1 uzerinden).
        """
        classical = next(
            (r for r in self.results if "klasik" in r.label.lower() or "classical" in r.label.lower()),
            None,
        )
        if classical is None or classical.local_mean <= 0:
            return {}

        return {
            r.label: 100.0 * (r.local_mean - classical.local_mean) / classical.local_mean
            for r in self.results
            if r is not classical
        }

    def as_table(self) -> str:
        satirlar = [
            "Prior karsilastirmasi (Makale, Extended Data Fig. 1a,b protokolu)",
            "-" * 78,
        ]
        satirlar.extend(str(r) for r in self.results)

        avantaj = self.quantum_advantage()
        if avantaj:
            satirlar.append("-" * 78)
            satirlar.append("Klasik taban cizgiye gore goreli iyilesme (local filter):")
            for label, value in avantaj.items():
                satirlar.append(f"  {label:<16} {value:+6.1f} %")
        return "\n".join(satirlar)


# ---------------------------------------------------------------------------
def _evaluate_samples(smiles_list: list[str]) -> tuple[float, float, float]:
    """Bir ornek kumesinin basari oranlarini olcer.

    Returns
    -------
    (local_filter_yuzdesi, chemistry42_yuzdesi, benzersizlik_yuzdesi)
    """
    if not smiles_list:
        return 0.0, 0.0, 0.0

    gecerli = [s for s in smiles_list if s]
    n = len(smiles_list)

    local = 100.0 * sum(1 for s in gecerli if passes_local_filter(s)) / n
    chem42 = 100.0 * sum(1 for s in gecerli if passes_chemistry42_filter(s)) / n
    benzersiz = 100.0 * len(set(gecerli)) / n if gecerli else 0.0

    return local, chem42, benzersiz


def _sample_smiles(generator: HybridGenerator, n: int) -> list[str]:
    """Uretici modelden n molekul cekip SMILES'e cevirir."""
    sonuc = generator.generate(n)
    return [s for s in sonuc.smiles]


def run_prior_benchmark(
    tokenizer: SelfiesTokenizer,
    training_sequences: np.ndarray,
    arms: tuple[str, ...] = ("classical", "quantum_sim"),
    config: Config | None = None,
    campaign: CampaignConfig | None = None,
    n_train_epochs: int = 5,
    n_samples: int | None = None,
    n_repeats: int | None = None,
    verbose: bool = True,
) -> PriorComparison:
    """Prior turlerini ayni protokolle karsilastirir.

    Makale protokolu: her yapilandirma 5 kez tekrarlanir, her tekrarda
    1.000 bilesik ornekleni r ve filtreden gecirilir; ortalama +/- std
    raporlanir.

    Parameters
    ----------
    arms
        Karsilastirilacak kollar. "quantum_hw" gercek IBM cihazi gerektirir.
    n_train_epochs
        Her kolun hibrit egitim dongusu adedi. Makaledeki 30 yerine kisa
        tutulabilir (kiyaslama goreli oldugu icin ayni deger tum kollara
        uygulandigi surece adildir).
    """
    config = config or Config()
    campaign = campaign or CampaignConfig()
    n_samples = n_samples or campaign.benchmark_samples_fig_a   # makale: 1.000
    n_repeats = n_repeats or campaign.benchmark_repeats          # makale: 5

    comparison = PriorComparison()

    for arm in arms:
        label = {
            "classical": "Klasik LSTM",
            "quantum_sim": "QCBM (SIM)",
            "quantum_hw": "QCBM (HW)",
        }.get(arm, arm)

        if verbose:
            logger.info("Kiyaslama kolu: %s", label)

        start = time.time()
        generator = HybridGenerator(arm=arm, tokenizer=tokenizer, config=config)

        # Egitim bir kez; tekrarlar ORNEKLEME uzerinde yapilir
        # (makale: "repeated the experiments five times, sampling n=1,000
        #  compounds in each repetition")
        generator.fit(
            training_sequences,
            n_epochs=n_train_epochs,
            n_generate_per_epoch=128,
            lstm_epochs_per_cycle=1,
            verbose=False,
        )

        result = BenchmarkResult(
            label=label,
            n_qubits=config.qcbm.n_qubits if arm != "classical" else None,
        )

        for repeat in range(n_repeats):
            smiles_list = _sample_smiles(generator, n_samples)
            local, chem42, benzersiz = _evaluate_samples(smiles_list)

            result.local_filter_rates.append(local)
            result.chemistry42_rates.append(chem42)
            result.uniqueness.append(benzersiz)

            if verbose:
                logger.info(
                    "  tekrar %d/%d: local %.2f %% | chem42 %.2f %%",
                    repeat + 1,
                    n_repeats,
                    local,
                    chem42,
                )

        result.duration_s = time.time() - start
        comparison.results.append(result)

        if verbose:
            logger.info("  %s", result)

    return comparison


def run_qubit_sweep(
    tokenizer: SelfiesTokenizer,
    training_sequences: np.ndarray,
    qubit_counts: tuple[int, ...] | None = None,
    config: Config | None = None,
    campaign: CampaignConfig | None = None,
    n_train_epochs: int = 3,
    n_samples: int = 1000,
    n_repeats: int = 3,
    verbose: bool = True,
) -> list[BenchmarkResult]:
    """Qubit sayisinin basari oranina etkisi (Makale, Extended Data Fig. 1c).

    Makale: "the success rate correlated roughly linearly with the number of
    qubits used in modeling the prior, indicating a direct relationship
    between the complexity of the quantum model and the effectiveness in
    generating high-quality molecules."

    NOT: Makale bu taramayi n=5.000 ornek ve 5 tekrarla yapar. Varsayilanlar
    burada daha kucuktur (hesaplama maliyeti); tam protokol icin
    campaign.benchmark_samples_fig_c ve campaign.benchmark_repeats kullanin.
    """
    from dataclasses import replace

    config = config or Config()
    campaign = campaign or CampaignConfig()
    qubit_counts = qubit_counts or campaign.qubit_sweep

    results: list[BenchmarkResult] = []

    for n_qubits in qubit_counts:
        if verbose:
            logger.info("Qubit taramasi: %d qubit", n_qubits)

        sweep_config = replace(config, qcbm=replace(config.qcbm, n_qubits=n_qubits))

        start = time.time()
        generator = HybridGenerator(
            arm="quantum_sim", tokenizer=tokenizer, config=sweep_config
        )
        generator.fit(
            training_sequences,
            n_epochs=n_train_epochs,
            n_generate_per_epoch=128,
            lstm_epochs_per_cycle=1,
            verbose=False,
        )

        result = BenchmarkResult(label=f"{n_qubits} qubit", n_qubits=n_qubits)

        for _ in range(n_repeats):
            local, chem42, benzersiz = _evaluate_samples(
                _sample_smiles(generator, n_samples)
            )
            result.local_filter_rates.append(local)
            result.chemistry42_rates.append(chem42)
            result.uniqueness.append(benzersiz)

        result.duration_s = time.time() - start
        results.append(result)

        if verbose:
            logger.info("  %s", result)

    return results


def fit_qubit_trend(results: list[BenchmarkResult]) -> dict[str, float]:
    """Qubit sayisi - basari orani iliskisine dogru uydurur.

    Makale, bu iliskinin "roughly linear" oldugunu bildirir
    (Extended Data Fig. 1c'deki kirmizi "Fit Line").
    """
    from scipy.stats import linregress

    qubits = np.array([r.n_qubits for r in results if r.n_qubits is not None], dtype=float)
    rates = np.array(
        [r.local_mean for r in results if r.n_qubits is not None], dtype=float
    )

    if len(qubits) < 3:
        return {}

    fit = linregress(qubits, rates)
    return {
        "slope": float(fit.slope),           # basari orani artisi / qubit
        "intercept": float(fit.intercept),
        "r_squared": float(fit.rvalue**2),
        "p_value": float(fit.pvalue),
    }
